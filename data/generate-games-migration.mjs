// Generate a Supabase migration that upserts the season's games (id +
// kickoff + team names + the full game JSON) into public.games, which the DB uses to enforce
// pick locks. Re-run after refetching the schedule, then `db push`:
//
//   node data/fetch-games.mjs 2026
//   node data/sync-to-apps.mjs 2026
//   node data/generate-games-migration.mjs 2026
//
// Each run writes a NEW timestamped migration (upserts are idempotent, so
// stacking refreshes is fine) — never overwrite an existing file: pushed
// migrations are recorded by version and an edited one would silently not
// re-apply.

import { readFileSync, writeFileSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const year = process.argv[2];
if (!year) {
  console.error('Usage: node data/generate-games-migration.mjs <year>');
  process.exit(1);
}

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const season = JSON.parse(readFileSync(join(root, 'data', `games-${year}.json`), 'utf8'));

const esc = (s) => (s == null ? 'null' : `'${String(s).replace(/'/g, "''")}'`);

// Rows match what the refresh-games Edge Function writes (hourly cron):
// time_tbd, the full normalized game in `data`, and refreshed_at = the
// moment this data was fetched from ESPN (the client overlays DB rows newer
// than its bundle's fetchedAt, so a bundle and its own seed never differ).
const json = (v) => `${esc(JSON.stringify(v))}::jsonb`;
const refreshedAt = season.fetchedAt ?? new Date().toISOString();

const rows = [];
for (const week of season.weeks) {
  for (const g of week.games) {
    if (!g.id || !g.date) continue;
    rows.push(
      `(${esc(g.id)}, ${season.season}, ${week.seasonType}, ${week.week}, ${esc(g.date)}, ` +
        `${esc(g.home?.school)}, ${esc(g.away?.school)}, ${esc(g.home?.abbrev)}, ${esc(g.away?.abbrev)}, ` +
        `${g.timeTbd === true}, ${json({ ...g, week: week.week, timeTbd: g.timeTbd === true })}, ${esc(refreshedAt)})`,
    );
  }
}

// Same guard as refresh-games: a game whose STORED kickoff has passed has
// locked and revealed its picks — moving its kickoff later would re-open
// them, so kickoff/time_tbd stay put and data.date mirrors the stored time.
const sql = `-- Auto-generated by data/generate-games-migration.mjs ${year}. Do not hand-edit.
insert into public.games (id, season, season_type, week, kickoff, home_school, away_school, home_abbrev, away_abbrev, time_tbd, data, refreshed_at)
values
${rows.join(',\n')}
on conflict (id) do update set
  season = excluded.season,
  season_type = excluded.season_type,
  week = excluded.week,
  kickoff = case when games.kickoff <= now() then games.kickoff else excluded.kickoff end,
  time_tbd = case when games.kickoff <= now() then games.time_tbd else excluded.time_tbd end,
  data = case when games.kickoff <= now()
    then excluded.data
      || jsonb_build_object(
        'date', to_char(games.kickoff at time zone 'UTC', 'YYYY-MM-DD"T"HH24:MI"Z"'),
        'timeTbd', games.time_tbd)
    else excluded.data end,
  refreshed_at = excluded.refreshed_at,
  home_school = excluded.home_school,
  away_school = excluded.away_school,
  home_abbrev = excluded.home_abbrev,
  away_abbrev = excluded.away_abbrev;
`;

const migrationsDir = join(root, 'supabase', 'migrations');
const stamp = new Date().toISOString().replace(/\D/g, '').slice(0, 14);
const file = join(migrationsDir, `${stamp}_games_${year}.sql`);
writeFileSync(file, sql);
console.log(`Wrote ${rows.length} games to ${file}`);
